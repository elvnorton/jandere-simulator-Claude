function phaseScene() {
  const p = S.phase;
  hideAll();
  setBG(p === 0 ? 'classroom' : 'hallway');
  tint(S.day === 4 ? 'rain' : ['day', 'noon', 'evening'][p]);
  particles(p === 2 ? 'dust' : null);
  AU.music(ambient());
}

async function runGame(resume) {
  $('#title').hidden = true;
  $('#toolbar').hidden = false;
  if (!resume) { S = newState(); await prologue(); S.day = 1; S.phase = -1; }
  else { setBG('classroom', null, true); showHUD(); }
  while (S.day <= 5) {
    if (S.phase < 0) {
      await dayStart(S.day);
      if (await checkFail()) return;
      S.phase = 0;
    }
    const nph = S.day === 5 ? 2 : 3;
    while (S.phase < nph) {
      saveGame(); updateHUD();
      phaseScene();
      if (!S.flags.helpShown) { S.flags.helpShown = 1; await new Promise(r => openHelp(r)); }
      const { loc, act } = await mapScreen(buildLocs());
      S.log[S.day] = S.log[S.day] || [];
      S.log[S.day][S.phase] = { loc: loc.id, name: loc.name, id: act.id, dark: !!act.dark };
      if (act.once) S.used[act.id] = 1;
      await act.run();
      hideAll();
      if (await checkFail()) return;
      S.phase++;
    }
    if (S.day === 5) break;
    await evening(S.day);
    if (await checkFail()) return;
    S.day++; S.phase = -1; saveGame();
  }
  await finale();
}

