function learn(k) { S.known[k] = 1; toast(`★ Ты узнала: ${TOPICS[k].t}`, '#ffd36a'); AU.sfx('clue'); }

async function talkGame(rounds) {
  for (let r = 0; r < rounds; r++) {
    const fresh = LIKES.filter(k => !S.topicUsed[k]);
    const like = fresh.length && Math.random() < .7 ? pick(fresh) : pick(LIKES);
    const keys = shuffle([like, pick(DISLIKES), ...shuffle(NEUTRAL).slice(0, 2)]);
    const opts = keys.map(k => ({ t: TOPICS[k].t + (S.known[k] ? ' ★' : ''), v: k }));
    if (S.sanity < 30) opts.push({ t: '«Почему ты всё время с ней?»', v: 'jealous', red: true });
    const k = await choice(opts, r === 0 ? 'О чём заговорить?' : 'Продолжить разговор…');
    if (k === 'jealous') {
      await me('Почему ты всё время с ней? С Юкиной?', 'yandere');
      await sp('sora', 'worried', 'С Юкиной? Мы просто вместе в клубе… Аманэ, ты в порядке? У тебя очень странный взгляд.');
      stat({ love: -6, sus: 4 });
      continue;
    }
    const T = TOPICS[k];
    await me(T.ask);
    let gain;
    if (T.like) {
      const again = S.topicUsed[k];
      if (again) await sp('sora', 'smile', 'Ты уже спрашивала… Но мне приятно, что ты помнишь.');
      else for (const [ex, t] of T.ans) await sp('sora', ex, t);
      gain = again ? 4 : 9;
      if (k === 'stars' && S.flags.starbook && !S.flags.starBonus) {
        S.flags.starBonus = 1; gain += 5;
        await me('Кольца Сатурна сейчас наклонены всего на несколько градусов — их видно хуже, чем обычно, да?');
        await sp('sora', 'surprised', 'Ты… это знаешь? Аманэ, ты меня удивляешь.');
      }
      S.topicUsed[k] = 1;
      if (!S.known[k]) learn(k);
    } else {
      for (const [ex, t] of T.ans) await sp('sora', ex, t);
      gain = T.dis ? -6 : 2;
    }
    stat({ love: gain });
  }
}

